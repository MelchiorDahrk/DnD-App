// Use the pinned 5e-bits JSON and text extracted from the official SRD 5.2.1 PDF.
// See docs/party-play.md for download locations and the extraction command.
import {readFile, writeFile} from 'node:fs/promises';
import {creatureTemplate} from '../encounter-model.js';

const [jsonPath, textPath] = process.argv.slice(2);
if (!jsonPath || !textPath) throw new Error('Usage: node scripts/build-creature-catalog.mjs MONSTERS.json SRD.txt');
const [json, pdf] = await Promise.all([readFile(jsonPath, 'utf8'), readFile(textPath, 'utf8')]);
const source = JSON.parse(json);
const key = name => name.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]/g, '');
const knownNames = new Set(source.map(entry => key(entry.name.split(',')[0])));
const initiative = new Map();
const lines = pdf.split(/\r?\n/);
for (const [index, line] of lines.entries()) {
  const match = line.match(/\bAC\s+\d+.*?Initiative\s*([+−-])\s*(\d+)\s*\(/);
  if (!match) continue;
  const name = lines.slice(Math.max(0, index - 4), index).map(key).reverse().find(value => knownNames.has(value));
  if (name) initiative.set(name, Number(match[2]) * (match[1] === '+' ? 1 : -1));
}
const abilities = {str: 'strength', dex: 'dexterity', con: 'constitution', int: 'intelligence', wis: 'wisdom', cha: 'charisma'};
const groups = {special_abilities: 'Trait', actions: 'Action', bonus_actions: 'Bonus action', reactions: 'Reaction', legendary_actions: 'Legendary action'};
const display = value => typeof value === 'object' ? value.name : value;
const list = values => values.map(display).join(', ');
const fields = object => Object.entries(object).map(([name, value]) => `${name.replaceAll('_', ' ')} ${value}`).join(', ');
function usage(uses, description = '') {
  if (uses?.type === 'recharge on roll') return {recharge: uses.min_value, reset: 'Recharge on d6'};
  if (uses?.times) return {max: uses.times, reset: uses.times_in_lair ? `Per day (${uses.times_in_lair} uses in lair)` : uses.type};
  if (uses?.type === 'recharge after rest') return {max: 1, reset: uses.rest_types?.join(' or ') || 'After rest'};
  if (/can[’']t take this action again until the start of its next turn/i.test(description))
    return {max: 1, reset: 'Start of its next turn'};
  return null;
}

const creatures = source.map(entry => {
  const proficiency = entry.proficiencies || [];
  const initiativeMod = initiative.get(key(entry.name.split(',')[0]));
  if (initiativeMod === undefined) throw new Error(`Missing SRD Initiative for ${entry.name}`);
  const actions = [];
  for (const [field, group] of Object.entries(groups)) {
    for (const action of entry[field] || []) {
      const spells = action.spellcasting?.spells || [];
      const spellList = spells.map(spell => spell.name + (spell.usage?.times ? ` (${spell.usage.times}/day)` : '')).join(', ');
      actions.push({
        group, name: action.name, description: action.desc + (spellList ? '\n' + spellList : ''),
        attack: action.attack_bonus, usage: usage(action.usage, action.desc),
        damage: (action.damage || []).map(part => ({formula: String(part.damage_dice).replace(/\s/g, ''), type: part.damage_type?.name}))
      });
      for (const spell of spells.filter(spell => spell.usage?.times)) {
        actions.push({group: 'Spell', name: spell.name, description: 'See Spellcasting and the spell rules.', usage: usage(spell.usage)});
      }
    }
  }
  return creatureTemplate({
    name: entry.name, source: 'SRD 5.2.1',
    stats: {
      size: entry.size, type: entry.type, alignment: entry.alignment, cr: entry.challenge_rating,
      ac: entry.armor_class[0].value, hp: entry.hit_points, initiativeMod,
      scores: Object.fromEntries(Object.entries(abilities).map(([short, long]) => [short, entry[long]])),
      saves: Object.fromEntries(proficiency.filter(item => item.proficiency.index.startsWith('saving-throw-'))
        .map(item => [item.proficiency.index.slice(-3), item.value])),
      skills: proficiency.filter(item => item.proficiency.index.startsWith('skill-'))
        .map(item => `${item.proficiency.name.replace(/^Skill: /, '')} ${item.value >= 0 ? '+' : ''}${item.value}`).join(', '),
      speed: fields(entry.speed), senses: fields(entry.senses), languages: entry.languages,
      resistances: list(entry.damage_resistances), immunities: list(entry.damage_immunities),
      vulnerabilities: list(entry.damage_vulnerabilities), conditionImmunities: list(entry.condition_immunities),
      description: entry.desc || `${entry.size} ${entry.type}, ${entry.alignment}.`, actions
    }
  }, `srd-${entry.index}`);
});

await writeFile(new URL('../creature-data.js', import.meta.url),
  '// Generated by scripts/build-creature-catalog.mjs. SRD 5.2.1, CC BY 4.0. See assets/creatures/SRD.md.\n' +
  'export const SRD_CREATURES = [\n' + creatures.map(entry => JSON.stringify(entry)).join(',\n') + '\n];\n');
console.log(`Generated ${creatures.length} SRD creature entries.`);
