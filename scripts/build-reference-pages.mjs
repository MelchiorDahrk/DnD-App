// Store public page paths, never rule text. Rebuild with --download to refresh indexes.
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..'),cache=resolve(root,'.tmp/reference-pages');
const indexes={
  '2014':['/','/spells','/lineage','/adventuring-gear','/armor','/weapons','/wondrous-items','/tools','/mounts-vehicles'],
  '2024':['/','/spell:all','/feat:all','/background:all','/species:all','/equipment:all','/magic-item:all']
};
const pages={};
for(const [edition,paths] of Object.entries(indexes)){
  const base=`https://dnd${edition==='2014'?'5e':'2024'}.wikidot.com`,found=new Set(['/']);
  await mkdir(resolve(cache,edition),{recursive:true});
  for(const path of paths){
    const file=resolve(cache,edition,encodeURIComponent(path)+'.html');
    if(process.argv.includes('--download')){
      const response=await fetch(base+path,{signal:AbortSignal.timeout(20000)});
      if(!response.ok)throw new Error(`${base+path}: ${response.status}`);
      await writeFile(file,await response.text());
    }
    const html=await readFile(file,'utf8');
    if(/page does not exist|page you want to access does not exist/i.test(html))throw new Error(`Missing wiki index: ${base+path}`);
    found.add(path);
    const body=(html.split('<div id="page-content">')[1]||'').split('<div class="page-tags">')[0];
    for(const match of body.matchAll(/href="([^"#?]+)(?:[?#][^"]*)?"/g)){
      let url;try{url=new URL(match[1],base);}catch{continue;}
      if(url.hostname!==new URL(base).hostname)continue;
      if(/^\/[a-z0-9-]+(?::[a-z0-9-]+)*$/.test(url.pathname)&&!/^\/(?:system|forum|nav|user-guide|legal|contact|about)(?::|$)/.test(url.pathname))found.add(url.pathname);
    }
  }
  pages[edition]=[...found].sort();
}
await writeFile(resolve(root,'reference-pages.js'),'// Public wiki index paths; generated by scripts/build-reference-pages.mjs.\n'+Object.entries(pages).map(([edition,paths])=>`export const PAGES_${edition}=${JSON.stringify(paths)};`).join('\n')+'\n');
console.log(`Indexed ${pages['2014'].length} earlier and ${pages['2024'].length} current wiki pages.`);
