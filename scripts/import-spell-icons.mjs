// Optional, network-only maintenance command. Normal builds use committed assets.
// Original path data is retained; only the opaque canvas path is removed.
import {writeFile,mkdir,readdir,unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {SPELL_ICON_ASSIGNMENTS,SCHOOL_SPELL_ICONS,EFFECT_SPELL_ICONS,UNKNOWN_SPELL_ICON} from '../spell-icon-mappings.js';

const root=resolve(import.meta.dirname,'..'),out=resolve(root,'assets/spell-icons');
const revision='82d948812bfe3f269ef8f731dcdb07b08160edc4';
const category={fire:'Fire',cold:'Ice',lightning:'Lightning',thunder:'Sound & wind',acid:'Acid & poison',poison:'Acid & poison',necrotic:'Death & spirits',radiant:'Divine & light',psychic:'Mind & enchantment',force:'Arcane energy',arcane:'Arcane & utility',healing:'Healing & life',protection:'Wards & protection',nature:'Nature & creatures',illusion:'Illusion',water:'Water'};
const entries=new Map();
for(const entry of [...SPELL_ICON_ASSIGNMENTS,...Object.values(SCHOOL_SPELL_ICONS),...Object.values(EFFECT_SPELL_ICONS),UNKNOWN_SPELL_ICON]){
  if(!entries.has(entry.key))entries.set(entry.key,{key:entry.key,tone:entry.tone,names:[]});
  entries.get(entry.key).names.push(...entry.names||[]);
}
const response=await fetch(`https://api.github.com/repos/game-icons/icons/git/trees/${revision}?recursive=1`);
if(!response.ok)throw new Error(`Upstream inventory: ${response.status}`);
const tree=(await response.json()).tree;
await mkdir(out,{recursive:true});
const manifest=[];
// Bounded parallel downloads, with explicit artist and source on every asset.
const pending=[...entries.values()];
await Promise.all(Array.from({length:8},async()=>{
  while(pending.length){
    const {key,tone,names}=pending.shift();
    const source=['lorc','delapouite'].map(artist=>`${artist}/${key}.svg`).find(path=>tree.some(entry=>entry.path===path));
    if(!source)throw new Error(`No upstream artwork for ${key}`);
    const url=`https://raw.githubusercontent.com/game-icons/icons/${revision}/${source}`;
    const response=await fetch(url);if(!response.ok)throw new Error(`${key}: ${response.status}`);
    const original=await response.text();
    if(!/^<svg\s/.test(original)||/<(?:script|foreignObject)|\bon\w+=|(?:href|url)\s*[:=(]/i.test(original))throw new Error(`Unexpected SVG: ${key}`);
    const svg=original.replace(/<path d="M0 0h512v512H0z"\s*\/>/,'');
    if(svg===original)throw new Error(`Unrecognized opaque canvas: ${key}`);
    await writeFile(resolve(out,`${key}.svg`),svg);
    const artist=source.startsWith('lorc/')?'Lorc':'Delapouite';
    manifest.push({key,label:key.split('-').map(word=>word[0].toUpperCase()+word.slice(1)).join(' '),group:category[tone],tone,keywords:names.join(' '),artist,
      source:`https://game-icons.net/1x1/${source.replace('.svg','.html')}`,sha256:createHash('sha256').update(svg).digest('hex')});
  }
}));
manifest.sort((a,b)=>a.label.localeCompare(b.label));
await writeFile(resolve(root,'spell-icon-manifest.js'),`// Generated by scripts/import-spell-icons.mjs from game-icons/icons @ ${revision}.\n// Artwork: CC BY 3.0. See assets/spell-icons/CREDITS.md.\nexport const SPELL_ICON_LIBRARY = ${JSON.stringify(manifest,null,2)};\nexport const SPELL_ICON_FILES = SPELL_ICON_LIBRARY.map(({key}) => \`./assets/spell-icons/\${key}.svg\`);\n`);
const credits=`# Spell artwork credits\n\nSelected artwork from [Game-icons.net](https://game-icons.net/), by [Lorc](https://lorcblog.blogspot.com/) and [Delapouite](https://delapouite.com/).\n\nLicensed under [Creative Commons Attribution 3.0 Unported](https://creativecommons.org/licenses/by/3.0/). You may share and adapt this artwork with attribution; no endorsement by the artists is implied.\n\nSource: [game-icons/icons @ ${revision}](https://github.com/game-icons/icons/tree/${revision}). Imported with scripts/import-spell-icons.mjs. Original SVG path geometry is preserved. The solid black canvas is removed for transparency; Questlog applies theme colors and a CSS glow at runtime.\n\n| Icon | Artist | Original |\n|---|---|---|\n${manifest.map(entry=>`| ${entry.label} | ${entry.artist} | [Source](${entry.source}) |`).join('\n')}\n`;
await writeFile(resolve(out,'CREDITS.md'),credits);
// Prune only obsolete SVGs in this dedicated asset directory, after a complete
// successful import. Never remove credits or unrelated files.
for(const file of await readdir(out))if(/^[a-z0-9-]+\.svg$/.test(file)&&!entries.has(file.slice(0,-4)))await unlink(resolve(out,file));
console.log(`Imported ${manifest.length} spell icons with per-asset attribution.`);
