import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {mkdir} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {resolve} from 'node:path';
import puppeteer from 'puppeteer-core';
import {makeCharacter,parseBackup,SAVE_VERSION} from '../model.js';
import {FEATURE_CATALOG,featureFields} from '../feature-catalog.js';
import {EQUIPMENT,itemFromEquipment} from '../catalog.js';
import {CONTENT_SOURCES,contentSourceIds} from '../content-sources.js';

const root=resolve(import.meta.dirname,'..'),port=process.env.SOURCE_TEST_PORT||'4201';
const base=process.env.SOURCE_TEST_URL||`http://127.0.0.1:${port}${process.env.SOURCE_TEST_PATH||'/'}`;
const executablePath=process.env.BROWSER_PATH||['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files/Mozilla Firefox/firefox.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe','/usr/bin/chromium'].find(existsSync);
assert.ok(executablePath,'Set BROWSER_PATH to a browser.');
const giantFeats=FEATURE_CATALOG.filter(entry=>entry.book==='Bigby Presents: Glory of the Giants');
const sourceId=contentSourceIds(giantFeats[0])[0];
const giantItem=EQUIPMENT.find(entry=>entry.category!=='Weapon'&&contentSourceIds(entry,'item').includes(sourceId));
let server,browser;
try {
  if(!process.env.SOURCE_TEST_URL){
    server=spawn(process.execPath,['scripts/serve.mjs'],{cwd:root,env:{...process.env,PORT:port},stdio:['ignore','pipe','pipe'],windowsHide:true});
    await new Promise((resolve,reject)=>{
      const timer=setTimeout(()=>reject(new Error('Test server did not start.')),10000);
      server.once('error',reject);server.once('exit',code=>reject(new Error(`Server exited: ${code}`)));
      server.stdout.once('data',()=>{clearTimeout(timer);resolve();});
      server.stderr.once('data',data=>reject(new Error(String(data))));
    });
  }
  browser=await puppeteer.launch({executablePath,browser:/firefox/i.test(executablePath)?'firefox':'chrome',headless:true,args:['--no-sandbox']});
  const page=await browser.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewport({width:1280,height:1000});
  await page.goto(base,{waitUntil:'networkidle0'});
  const character=makeCharacter({name:'Giant source check',class:'Fighter',level:3});
  character.features=['Strike of the Giants','Guile of the Cloud Giant'].map((name,i)=>({id:`feat-${i}`,used:0,...featureFields(giantFeats.find(entry=>entry.name===name),character)}));
  character.items=[{...itemFromEquipment(giantItem),id:'giant-item'}];
  await page.evaluate(state=>localStorage.setItem('questlog.v2',JSON.stringify(state)),{version:SAVE_VERSION,characters:[character],activeId:character.id,settings:{sound:false}});
  await page.reload({waitUntil:'networkidle0'});
  const state=async()=>parseBackup(await page.evaluate(()=>localStorage.getItem('questlog.v2')));
  const click=selector=>page.$eval(selector,node=>node.click());
  const close=()=>click('#modal [data-action="close"]');
  const navigate=route=>click(`[data-action="navigate"][data-route="${route}"]`);
  const options=selector=>page.$$eval(`${selector} option`,nodes=>nodes.map(node=>node.value));
  const search=async(selector,value)=>page.$eval(selector,(node,value)=>{node.value=value;node.dispatchEvent(new Event('input',{bubbles:true}));},value);
  const openFeatures=()=>click('[data-action="feature"]:not([data-id])');
  const featureOptions=()=>options('[data-catalog-pick="feat"]');

  await openFeatures();await page.select('[data-catalog-scope="feat"]','all');
  for(const entry of giantFeats)assert.ok((await featureOptions()).includes(entry.id),entry.name);
  await page.select('[data-catalog-source="feat"]','Bigby Presents: Glory of the Giants');
  assert.equal((await featureOptions()).length,9,'all eight giant feats can be added');
  await close();await navigate('settings');
  const before=(await state()).characters;
  await click(`[data-content-source="${sourceId}"]`);
  assert.deepEqual((await state()).settings.hiddenSources,[sourceId]);
  assert.deepEqual((await state()).characters,before,'source toggle preserves every saved entry');
  await page.reload({waitUntil:'networkidle0'});
  assert.equal(await page.$eval(`[data-content-source="${sourceId}"]`,node=>node.checked),false);
  await search('[data-source-search]','giants');
  assert.equal(await page.$$eval('[data-source-row]:not([hidden])',nodes=>nodes.length),1);
  for(const width of [390,320]){
    await page.setViewport({width,height:900});
    assert.ok(await page.$eval('.content-source-settings',node=>node.scrollWidth<=node.clientWidth));
    await mkdir(resolve(root,'.tmp'),{recursive:true});
    await (await page.$('.content-source-settings')).screenshot({path:resolve(root,`.tmp/content-sources-${width}.png`)});
  }
  await page.setViewport({width:1280,height:1000});
  await navigate('sheet');await openFeatures();
  for(const entry of giantFeats)assert.ok(!(await featureOptions()).includes(entry.id));
  await page.select('[data-catalog-scope="feat"]','all');await search('[data-catalog-search="feat"]','giant');
  for(const entry of giantFeats)assert.ok(!(await featureOptions()).includes(entry.id));
  assert.ok(!(await options('[data-catalog-source="feat"]')).includes('Bigby Presents: Glory of the Giants'));
  await close();
  await click('[data-action="feature"][data-id="feat-1"]');
  assert.equal(await page.$eval('#modal [name="name"]',node=>node.value),'Guile of the Cloud Giant');
  await click('#modal button[type="submit"]');
  await click('[data-action="feature-use"][data-id="feat-1"][data-used="1"]');
  assert.equal((await state()).characters[0].features[1].used,1,'hidden-source feats remain usable');
  await navigate('inventory');await click('[data-action="item"]:not([data-id])');
  assert.ok(!(await options('[data-catalog-pick="item"]')).includes(giantItem.id));
  await search('[data-catalog-search="item"]',giantItem.name);
  assert.equal((await options('[data-catalog-pick="item"]')).length,1);
  await close();await click('[data-action="item"][data-id="giant-item"]');
  assert.equal(await page.$eval('#modal [name="name"]',node=>node.value),giantItem.name);
  await click('#modal button[type="submit"]');
  assert.deepEqual((await state()).characters[0].items,before[0].items,'hidden-source items remain editable');
  await navigate('wiki');await page.select('[data-reference-kind]','Feats');
  for(const entry of giantFeats)assert.ok(!(await options('[data-reference-entry]')).includes(entry.id));
  await page.select('[data-reference-kind]','Magic items');
  assert.ok(!(await options('[data-reference-entry]')).includes(giantItem.id));
  await navigate('sheet');await click('[data-action="level-up"]');
  for(const entry of giantFeats)assert.ok(!(await options('[name="choice-feat"]')).includes(entry.id));
  await search('[data-level-feat-search]','giant');
  assert.equal((await options('[name="choice-feat"]')).length,1);
  await close();
  await navigate('settings');await click(`[data-content-source="${sourceId}"]`);
  await navigate('sheet');await click('[data-action="level-up"]');
  assert.ok((await options('[name="choice-feat"]')).includes(giantFeats.find(entry=>entry.name==='Vigor of the Hill Giant').id));
  await close();
  await navigate('settings');await click('[data-action="sources-none"]');
  assert.equal((await state()).settings.hiddenSources.length,CONTENT_SOURCES.length);
  await navigate('inventory');await click('[data-action="item"]:not([data-id])');
  assert.equal((await options('[data-catalog-pick="item"]')).length,1);
  await close();await navigate('sheet');await click('[data-action="edit-character"]');
  assert.equal(await page.$eval('[name="class"]',node=>node.value),'Fighter','existing class stays selected with its source disabled');
  await close();await navigate('settings');await click('[data-action="sources-all"]');
  assert.deepEqual((await state()).settings.hiddenSources,[]);
  await click(`[data-content-source="${sourceId}"]`);
  await page.waitForFunction(()=>navigator.serviceWorker.controller);
  await page.setOfflineMode(true);await page.reload({waitUntil:'networkidle0'});
  assert.equal(await page.$eval(`[data-content-source="${sourceId}"]`,node=>node.checked),false);
  await navigate('sheet');await openFeatures();await page.select('[data-catalog-scope="feat"]','all');
  for(const entry of giantFeats)assert.ok(!(await featureOptions()).includes(entry.id));
  assert.deepEqual(errors,[]);
  console.log('PASS source settings persistence, all eight giant feats, initial/search/compendium/level-up filtering, existing content edit/use, 320px/390px layouts, enable/disable all and offline reload');
} finally {await browser?.close();server?.kill();}
