import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {mkdir} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {resolve} from 'node:path';
import puppeteer from 'puppeteer-core';
import {makeCharacter,parseBackup,SAVE_VERSION} from '../model.js';
import {findEquipment,itemFromEquipment} from '../catalog.js';

const root=resolve(import.meta.dirname,'..'),port=process.env.INVENTORY_TEST_PORT||'4197',base=`http://127.0.0.1:${port}/`;
const executablePath=process.env.BROWSER_PATH||['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files/Mozilla Firefox/firefox.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe','/usr/bin/google-chrome','/usr/bin/chromium'].find(existsSync);
assert.ok(executablePath,'Set BROWSER_PATH to a browser.');
let server,browser,calmBrowser;
try {
  server=spawn(process.execPath,['scripts/serve.mjs'],{cwd:root,env:{...process.env,PORT:port},stdio:['ignore','pipe','pipe'],windowsHide:true});
  await new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(Error('Test server did not start')),10000);
    server.once('error',error=>{clearTimeout(timer);reject(error);});
    server.once('exit',code=>{clearTimeout(timer);reject(Error(`Server exited (${code})`));});
    server.stdout.once('data',()=>{clearTimeout(timer);resolve();});
    server.stderr.once('data',data=>{clearTimeout(timer);reject(Error(String(data)));});
  });
  browser=await puppeteer.launch({executablePath,browser:/firefox/i.test(executablePath)?'firefox':'chrome',headless:true,args:['--no-sandbox']});
  const page=await browser.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewport({width:1280,height:950});
  await page.goto(base,{waitUntil:'networkidle0'});
  const c=makeCharacter({name:'Inventory test'}),pack={...itemFromEquipment(findEquipment('explorers-pack')),id:'pack',qty:2};
  const kit={...itemFromEquipment(findEquipment('healers-kit')),id:'kit'};
  delete kit.maxUses;delete kit.usesLeft;delete kit.consumeOnEmpty;
  c.items=[pack,kit,{...itemFromEquipment(findEquipment('torch')),id:'torch',qty:3}];
  c.sheetLayout={collapsed:[],favorites:{pack:['pack','kit']}};
  await page.evaluate(state=>localStorage.setItem('questlog.v2',JSON.stringify(state)),{version:SAVE_VERSION,characters:[c],activeId:c.id,settings:{sound:false}});
  await page.goto(base+'#inventory');await page.reload({waitUntil:'networkidle0'});
  const saved=async()=>parseBackup(await page.evaluate(()=>localStorage.getItem('questlog.v2'))).characters[0];
  const button=(action,id)=>`#main [data-action="${action}"][data-id="${id}"]`;
  const use=async id=>{await page.click(button('use-item',id));await page.click('#modal [data-action="confirm-use-item"]');};
  const edit=async(id,values)=>{
    await page.click(button('item',id));
    await page.evaluate(values=>{for(const [name,value] of Object.entries(values)){const input=document.querySelector(`#modal [name="${name}"]`);if(input.type==='checkbox')input.checked=value;else input.value=value;}},values);
    await page.click('#modal button[type="submit"]');
  };
  const unpack=async()=>{await page.click(button('unpack-item','pack'));await page.click('#modal [data-action="confirm-unpack-item"]');};
  await mkdir(resolve(root,'.tmp'),{recursive:true});
  console.log('RUN unpack preview, stacking, animation, favorites and persistence');
  await page.click(button('unpack-item','pack'));
  assert.equal(await page.$$eval('.unpack-contents li',rows=>rows.length),8);
  assert.match(await page.$eval('.unpack-contents',node=>node.textContent),/Torch×10/);
  await page.click('#modal [data-action="close"]');assert.equal((await saved()).items.find(i=>i.id==='pack').qty,2);
  await unpack();
  await page.waitForSelector('[data-effect="unpack"] .vfx-unpack-supply');
  assert.equal(await page.$$eval('.vfx-unpack-supply',nodes=>nodes.length),8);
  await page.waitForFunction(()=>document.querySelector('.vfx-unpack-supply')?.getAnimations()[0]?.currentTime>600);
  await page.screenshot({path:resolve(root,'.tmp/inventory-unpack-desktop.png')});
  let current=await saved();assert.equal(current.items.find(i=>i.id==='pack').qty,1);assert.equal(current.items.find(i=>i.id==='torch').qty,13);
  await page.setViewport({width:390,height:844});
  await page.$eval(button('unpack-item','pack'),node=>node.scrollIntoView({block:'center',behavior:'instant'}));
  await page.click(button('unpack-item','pack'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:resolve(root,'.tmp/inventory-unpack-preview-mobile.png')});
  await page.click('#modal [data-action="confirm-unpack-item"]');
  await page.waitForFunction(()=>document.querySelector('.vfx-unpack-supply')?.getAnimations()[0]?.currentTime>600);
  await page.screenshot({path:resolve(root,'.tmp/inventory-unpack-mobile.png')});
  assert.equal((await saved()).items.find(i=>i.id==='pack').qty,0);
  assert.equal(await page.$eval(button('unpack-item','pack'),node=>node.disabled),true);
  await page.click('[data-action="sheet-favorite"][data-entry="pack"]');assert.equal((await saved()).items.some(i=>i.id==='pack'),false);
  await page.reload({waitUntil:'networkidle0'});assert.equal((await saved()).items.find(i=>i.id==='torch').qty,23);

  console.log('RUN healer kit defaults, depletion, replenishment and custom rechargeable uses');
  assert.match(await page.$eval('[data-inventory-item="kit"] .item-uses',node=>node.textContent),/10 \/ 10 uses/);
  await use('kit');assert.equal((await saved()).items.find(i=>i.id==='kit').usesLeft,9);
  await page.reload({waitUntil:'networkidle0'});assert.match(await page.$eval('[data-inventory-item="kit"] .item-uses',node=>node.textContent),/9 \/ 10/);
  await edit('kit',{usesLeft:1});await use('kit');assert.equal((await saved()).items.find(i=>i.id==='kit').qty,0);
  assert.equal(await page.$eval(button('use-item','kit'),node=>node.disabled),true);
  await page.click(button('quantity','kit')+'[data-delta="1"]');assert.equal((await saved()).items.find(i=>i.id==='kit').usesLeft,10);
  await page.click('[data-action="sheet-favorite"][data-entry="kit"]');
  await edit('kit',{usesLeft:1});await use('kit');assert.equal((await saved()).items.some(i=>i.id==='kit'),false);
  await edit('torch',{maxUses:3,usesLeft:1,consumeOnEmpty:false});await use('torch');
  current=await saved();assert.equal(current.items.find(i=>i.id==='torch').qty,23);assert.equal(current.items.find(i=>i.id==='torch').usesLeft,0);
  assert.equal(await page.$eval(button('use-item','torch'),node=>node.disabled),true);
  await edit('torch',{qty:0});assert.equal((await saved()).items.some(i=>i.id==='torch'),false);
  const bedroll=(await saved()).items.find(i=>i.name==='Bedroll');
  await page.click(button('quantity',bedroll.id)+'[data-delta="-1"]');await page.click(button('quantity',bedroll.id)+'[data-delta="-1"]');
  assert.equal((await saved()).items.some(i=>i.id===bedroll.id),false);

  console.log('RUN catalog defaults, offline unpack, reduced motion, sheet actions');
  await page.click('[data-action="item"]:not([data-id])');
  await page.select('[data-catalog-pick="item"]','healers-kit');
  assert.equal(await page.$eval('#modal [name="maxUses"]',node=>node.value),'10');
  assert.equal(await page.$eval('#modal [name="consumeOnEmpty"]',node=>node.checked),true);
  await page.select('[data-catalog-pick="item"]','explorers-pack');
  assert.equal(await page.$eval('#modal [name="maxUses"]',node=>node.value),'0');
  await page.click('#modal button[type="submit"]');
  const newPack=(await saved()).items.find(i=>i.name==='Explorer’s Pack');
  await page.evaluate(()=>navigator.serviceWorker.register('./sw.js',{type:'module'}).then(()=>true));
  await page.waitForFunction(()=>navigator.serviceWorker.controller,{timeout:30000});
  await page.setOfflineMode(true);await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForSelector(button('unpack-item',newPack.id));
  await page.click(button('unpack-item',newPack.id));await page.click('#modal [data-action="confirm-unpack-item"]');
  assert.equal((await saved()).items.some(i=>i.id===newPack.id),false);
  await page.reload({waitUntil:'domcontentloaded'});await page.waitForSelector('.inventory-list');assert.ok((await saved()).items.some(i=>i.name==='Backpack'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:resolve(root,'.tmp/inventory-mobile.png')});
  await page.setOfflineMode(false);
  console.log('PASS offline unpack and reload; RUN reduced-motion browser');
  if(/firefox/i.test(executablePath))calmBrowser=await puppeteer.launch({executablePath,browser:'firefox',headless:true,extraPrefsFirefox:{'ui.prefersReducedMotion':1}});
  const calmPage=await (calmBrowser||browser).newPage();
  if(!calmBrowser)await calmPage.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
  calmPage.on('pageerror',error=>errors.push(error.message));
  await calmPage.goto(base,{waitUntil:'networkidle0'});
  await calmPage.evaluate(state=>localStorage.setItem('questlog.v2',JSON.stringify(state)),{version:SAVE_VERSION,characters:[c],activeId:c.id,settings:{sound:false}});
  await calmPage.goto(base+'#inventory');await calmPage.reload({waitUntil:'networkidle0'});
  assert.equal(await calmPage.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches),true);
  await calmPage.click(button('unpack-item','pack'));await calmPage.click('#modal [data-action="confirm-unpack-item"]');
  assert.ok(await calmPage.$('[data-effect="unpack"].vfx-calm'));
  assert.equal(await calmPage.$('.vfx-unpack-supply'),null);
  assert.deepEqual(errors,[]);
  console.log('PASS inventory unpacking, uses, favorites, persistence, mobile, reduced motion and offline.');
}finally{await calmBrowser?.close();await browser?.close();server?.kill();}
